CREATE TABLE IF NOT EXISTS sales_contract_sales_detail_entry (
  FSEQ INT NOT NULL COMMENT '单据分录序列号',
  FID VARCHAR(64) NOT NULL COMMENT 'ID',
  FPARENTID VARCHAR(64) NULL COMMENT '单据头',
  CFMATERIALCODEID VARCHAR(64) NULL COMMENT '物料编码',
  CFMATERIALNAME VARCHAR(255) NULL COMMENT '物料名称',
  CFUNITID VARCHAR(64) NULL COMMENT '',
  CFTRANSPORTWAY VARCHAR(64) NULL COMMENT '',
  CFNUM DECIMAL(18, 6) NULL COMMENT '数量',
  CFTOTALSINGLEPRICE DECIMAL(18, 6) NULL COMMENT '总单价',
  CFREMARK VARCHAR(1024) NULL COMMENT '备注',
  CFPROJECTNAMEID VARCHAR(64) NULL COMMENT '',
  CFTRANSPORTSINGLEPRICE DECIMAL(18, 6) NULL COMMENT '运输单价',
  CFSALEPRICETYPEID VARCHAR(64) NULL COMMENT '销售价格类型',
  CFSTOPSTATUS TINYINT NULL COMMENT '是否停用',
  CFTRANSPORTID VARCHAR(64) NULL COMMENT '承运商',
  CFMODEL VARCHAR(255) NULL COMMENT '规格型号',
  CFFIRSTBILLTIME DATETIME NULL COMMENT '首次开单时间',
  CFDELIVERYTYPEID VARCHAR(64) NULL COMMENT '交货方式',
  CFPROJECTID VARCHAR(64) NULL COMMENT '项目',
  CFUNIT VARCHAR(64) NULL COMMENT '计量单位',
  CFENDTIME DATE NULL COMMENT '结束日期',
  CFWAREHOUSEID VARCHAR(64) NULL COMMENT '仓库',
  CFEXTRAPROTOCOLNUM VARCHAR(255) NULL COMMENT '补充协议号',
  CFGIFTID VARCHAR(64) NULL COMMENT '赠品',
  CFTRANSPORTPRICETY VARCHAR(64) NULL COMMENT '运输价格类型',
  CFSALESINGLEPRICE DECIMAL(18, 6) NULL COMMENT '销售单价',
  CFSTARTTIME DATETIME NULL COMMENT '开始日期',
  CFUPDATESTATUS TINYINT NULL COMMENT '是否更新',
  CFEXECUTETRANSPORTPRICE DECIMAL(18, 6) NULL COMMENT '执行运价',
  CFEXECUTETOTALSINGLEPRICE DECIMAL(18, 6) NULL COMMENT '执行总单价',
  CFEXECUTESALEPRICE DECIMAL(18, 6) NULL COMMENT '执行销价',
  CFORIGINENTRYID VARCHAR(64) NULL COMMENT '原分录id',
  CFAMOUNT DECIMAL(18, 2) NULL COMMENT '金额',
  CFEXECUTETECHNOLOGYREMARK VARCHAR(1024) NULL COMMENT '执行标准及技术要求',
  CFREGIONID VARCHAR(64) NULL COMMENT '区域',
  CFPRINTSTATUSENTRY TINYINT NULL COMMENT '是否打印铁路标准',
  CFCUSTOMSORTID VARCHAR(64) NULL COMMENT '客户细分',
  CFNOTES VARCHAR(1024) NULL COMMENT '新备注',
  CFTAXRATE DECIMAL(10, 4) NULL COMMENT '税率',
  CFCEMENTBRAND VARCHAR(64) NULL COMMENT '水泥品牌'
)
PRIMARY KEY (FSEQ, FID)
DISTRIBUTED BY HASH(FSEQ, FID) BUCKETS 10
PROPERTIES (
  "replication_num" = "3"
);
